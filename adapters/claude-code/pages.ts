/** Programs that hand a file to the desktop's browser, or are one. */
const OPENERS = new Set(["xdg-open", "open", "sensible-browser", "x-www-browser", "www-browser", "wslview", "start"]);
const BROWSERS = new Set([
  "firefox",
  "firefox-esr",
  "google-chrome",
  "google-chrome-stable",
  "chromium",
  "chromium-browser",
  "chrome",
  "brave",
  "brave-browser",
  "microsoft-edge",
  "microsoft-edge-stable",
  "msedge",
  "vivaldi",
  "opera",
  "epiphany",
]);
/** What runs the program after it: `nohup xdg-open …`, `env A=1 firefox …`. */
const WRAPPERS = new Set(["nohup", "setsid", "command", "exec", "env"]);
/** A browser run for a program, not for the developer: nothing is shown. */
const UNSEEN = /^--(?:headless|screenshot|print-to-pdf|dump-dom)\b/;
const HTML = /\.html?$/i;

/**
 * Folders whose pages are generated by tools (dependencies, coverage and test reports, an app's build
 * output, virtual environments): a preview of the tool or the app, not a page made for the developer
 * to review, and most load files beside them that a review does not carry.
 */
const GENERATED = new Set([
  "node_modules",
  "bower_components",
  "vendor",
  "coverage",
  "htmlcov",
  "lcov-report",
  ".nyc_output",
  "playwright-report",
  "test-results",
  "blob-report",
  "allure-report",
  "mochawesome-report",
  "dist",
  "build",
  "out",
  ".next",
  ".nuxt",
  ".svelte-kit",
  "target",
  "_site",
  "storybook-static",
  ".git",
  ".venv",
  "venv",
  "site-packages",
]);

type Word = { text: string; literal: boolean };

/**
 * The words of each simple command in a shell command line, split at `;`, `&&`, `||`, `|`, `&` and
 * line breaks outside quotes. A word holding an expansion (`$…`, backquotes) is not literal: what it
 * names is known only to the shell.
 */
function commands(line: string): Word[][] {
  const out: Word[][] = [];
  let words: Word[] = [];
  let word: Word | undefined;
  const take = () => {
    if (word) words.push(word);
    word = undefined;
  };
  const end = () => {
    take();
    if (words.length > 0) out.push(words);
    words = [];
  };
  for (let i = 0; i < line.length; i++) {
    const c = line.charAt(i);
    if (c === "'") {
      const close = line.indexOf("'", i + 1);
      const to = close < 0 ? line.length : close;
      word = { text: (word?.text ?? "") + line.slice(i + 1, to), literal: word?.literal ?? true };
      i = to;
    } else if (c === '"') {
      word ??= { text: "", literal: true };
      for (i++; i < line.length && line.charAt(i) !== '"'; i++) {
        const d = line.charAt(i);
        if (d === "\\" && i + 1 < line.length) word.text += line.charAt(++i);
        else {
          if (d === "$" || d === "`") word.literal = false;
          word.text += d;
        }
      }
    } else if (c === "\\" && i + 1 < line.length) {
      if (line.charAt(i + 1) === "\n") i++;
      else word = { text: (word?.text ?? "") + line.charAt(++i), literal: word?.literal ?? true };
    } else if (c === "#" && word === undefined) {
      const next = line.indexOf("\n", i);
      i = next < 0 ? line.length : next - 1;
    } else if (";&|\n()".includes(c)) {
      end();
    } else if (c === " " || c === "\t") {
      take();
    } else {
      word = { text: (word?.text ?? "") + c, literal: (word?.literal ?? true) && c !== "$" && c !== "`" };
    }
  }
  end();
  return out;
}

/**
 * The local HTML files a shell command line opens in a browser for the developer to see: what
 * `xdg-open`, `open`, `start`, `gio open`, `sensible-browser`, `wslview`, `python -m webbrowser` or a
 * browser binary (not headless) is given, as a path ending in `.html` or `.htm` or a `file:` URL. A
 * relative path is resolved against the folder the command runs in after its `cd`s, then against
 * `cwd` itself (the hook may report the folder the `cd` already moved to): its candidates, in that
 * order. A word the shell would expand is left out.
 */
export function openedPages(line: string, cwd: string, home: string | undefined): string[][] {
  const found = new Map<string, string[]>();
  let dir = cwd;
  const expand = (w: Word) => (w.text === "~" || w.text.startsWith("~/") ? (home === undefined ? undefined : path.join(home, w.text.slice(1))) : w.text);
  for (const command of commands(line)) {
    let words = command;
    while (words[0] !== undefined && words.length > 1 && (WRAPPERS.has(words[0].text) || /^[A-Za-z_]\w*=/.test(words[0].text))) words = words.slice(1);
    if (words[0]?.text === "cd") {
      const to = words[1] === undefined ? home : words[1].literal ? expand(words[1]) : undefined;
      if (to !== undefined) dir = path.resolve(dir, to);
      continue;
    }
    const program = path.basename(words[0]?.text ?? "");
    let args: Word[];
    if (OPENERS.has(program) || BROWSERS.has(program)) args = words.slice(1);
    else if (program === "gio" && words[1]?.text === "open") args = words.slice(2);
    else if (/^python(?:\d+(?:\.\d+)?)?$/.test(program) && words.some((w, i) => w.text === "-m" && words[i + 1]?.text === "webbrowser")) args = words.slice(words.findIndex((w) => w.text === "webbrowser") + 1);
    else continue;
    if (args.some((w) => UNSEEN.test(w.text))) continue;
    for (const arg of args) {
      const value = arg.literal ? expand(arg) : undefined;
      const file = localFile(value, dir);
      if (file === undefined || value === undefined) continue;
      found.set(file, [...new Set([file, ...(path.isAbsolute(value) || /^file:/i.test(value) ? [] : [path.resolve(cwd, value)])])]);
    }
  }
  return [...found.values()];
}

/** The file a browser argument names, when it is a local HTML file: a path, or a `file:` URL. */
function localFile(value: string | undefined, dir: string): string | undefined {
  if (value === undefined || value.startsWith("-")) return undefined;
  if (/^file:/i.test(value)) {
    let file: string;
    try {
      file = fileURLToPath(new URL(value));
    } catch {
      return undefined; // a file: URL the platform cannot read as a local path names no page
    }
    return HTML.test(file) ? file : undefined;
  }
  if (/^[a-z][a-z0-9+.-]*:/i.test(value) || !HTML.test(value)) return undefined;
  return path.resolve(dir, value);
}

/**
 * Why a page (its real path) is not published on its own: it lies outside the session's project, its
 * worktrees and the temporary folders (`temp`), or under a folder of generated pages. Undefined when
 * it is published.
 */
export function notPublished(file: string, session: Pick<Session, "project">, temp = [...new Set(["/tmp", os.tmpdir()].map(realOr))]): string | undefined {
  const project = realOr(session.project.dir);
  // A file in a linked worktree of the project reads as the same file of its main checkout.
  const mapped = locateProject(path.dirname(file)).dir;
  const root = within(mapped, project) ? project : temp.find((t) => within(file, t));
  if (root === undefined) return "outside the session's project, its worktrees and the temporary folder";
  const relative = path.relative(root, root === project ? path.join(mapped, path.basename(file)) : file);
  const generated = relative.split(path.sep).find((part) => GENERATED.has(part));
  if (generated !== undefined) return `under ${generated}/, where tools write their pages`;
  return undefined;
}

/** The real path of `file`, or undefined when there is none. */
function existing(file: string): string | undefined {
  try {
    return fs.realpathSync(file);
  } catch (error) {
    if (isCode(error, "ENOENT") || isCode(error, "ENOTDIR")) return undefined; // the browser was handed a page that does not exist
    throw error;
  }
}

const within = (file: string, dir: string) => file === dir || file.startsWith(`${dir}${path.sep}`);

function realOr(dir: string): string {
  try {
    return fs.realpathSync(dir);
  } catch (error) {
    if (isCode(error, "ENOENT")) return path.resolve(dir); // a folder gone since: compared as written
    throw error;
  }
}

/**
 * Publishes the local pages a session's shell command opened in a browser, each as `agent-desk review
 * "<its title>" --page <file>` would (the same inlining, limits and next round by title), unless the
 * session published that file already this turn, or the page is the same as its review's latest
 * round. A page that is not published says why in `problems` when the reason is the page's own (too
 * large, unreadable, made of several files); one not meant for a review is left quietly.
 */
export function publishOpenedPages(store: Store, sessionId: string, line: string, cwd: string, home: string | undefined, problems: string[]): Review[] {
  const session = store.getSession(sessionId);
  if (!session) return [];
  const published: Review[] = [];
  for (const candidates of openedPages(line, cwd, home)) {
    const file = candidates.map(existing).find((f) => f !== undefined);
    // A page that does not exist, a folder, or a page not made for the developer to review (see
    // notPublished) is the session's own business: nothing to publish.
    if (file === undefined || !fs.statSync(file).isFile() || notPublished(file, session) !== undefined) continue;
    if (publishedThisTurn(store, session, file, problems)) continue;
    try {
      const page = inlinePage(file);
      const assets = localAssets(page.html);
      if (assets.length > 0) {
        problems.push(`the page ${file} opened in the browser was not published as a review: it loads ${assets.slice(0, 3).join(", ")} from beside it, and a review keeps one file (publish a page that holds its scripts and styles, with agent-desk review --page)`);
        continue;
      }
      const title = pageTitle(page.html, file);
      if (sameAsLatest(store, session, title, page.html, problems)) continue;
      published.push(store.publishReview({ sessionId, title, html: page.html, page: file }));
      for (const s of page.skipped) problems.push(`review page ${file}: left as is, ${s.reason}: ${s.ref}`);
    } catch (error) {
      problems.push(`the page ${file} opened in the browser was not published as a review: ${(error as Error).message}`);
    }
  }
  return published;
}

/** Whether the session published that very file in its current turn (its last turn's end on). */
function publishedThisTurn(store: Store, session: Session, file: string, problems: string[]): boolean {
  const since = session.turnEndedAt ?? "";
  return store.listReviews(problems).some((r) => r.rounds.some((round) => round.page === file && round.sessionId === session.id && round.at > since));
}

/** Whether the review this page would continue already shows it, unchanged, as its latest round. */
function sameAsLatest(store: Store, session: Session, title: string, html: string, problems: string[]): boolean {
  const open = store.listReviews(problems).find((r) => !r.closedAt && r.project.dir === session.project.dir && r.title.toLowerCase() === title.toLowerCase());
  return open !== undefined && store.reviewPage(open.id)?.html === html;
}
